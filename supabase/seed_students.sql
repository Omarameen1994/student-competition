do $$
declare r record;
begin
  for r in
    select s.id from students s
     where s.competition_id = 'a1b2c3d4-0000-4000-8000-000000000001'
       and not exists (select 1 from student_credentials c where c.student_id = s.id)
     order by s.created_at
  loop
    insert into student_credentials (student_id, login_code)
    values (r.id, generate_login_code());
  end loop;
end $$;

